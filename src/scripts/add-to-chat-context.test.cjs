const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const source = file => fs.readFileSync(path.join(__dirname, '../src', file), 'utf8')

test('Add to chat stages attachments and focuses composer without submitting or replacing the draft', () => {
  const chat = source('components/organisms/ClawdChat/index.tsx')
  const add = chat.slice(chat.indexOf('  const addSelectedQuote ='), chat.indexOf('  const [isDragOver'))
  assert.match(add, /quote\.conversationId !== quoteConversationRef\.current/)
  assert.match(add, /appendChatQuote\(previous, quote\)/)
  assert.match(add, /chatInputElementRef\.current\?\.focus\(\)/)
  assert.doesNotMatch(add, /doSend|onSend|sendMessage|initialValue|\.value\s*=|setScheduleDraft/)
  assert.match(chat, /<ChatSelectionActions rootRef=\{chatBodyRef\}/)
  assert.match(chat, /data-chat-quote-message-id=\{m\.id\}/)
})
test('composer and queue send scoped snapshots; background sends cannot consume staged quotes', () => {
  const chat = source('components/organisms/ClawdChat/index.tsx')
  assert.match(chat, /doSendRef\.current\?\.\(text, undefined, true\)/)
  const send = chat.slice(chat.indexOf('  const doSend = async'), chat.indexOf('    const notificationText =', chat.indexOf('  const doSend = async')))
  assert.match(send, /attachmentOverride\?\.some\(file => file\.chatQuote && file\.chatQuote\.conversationId !== quoteScopeAtSend\)/)
  assert.match(send, /chatAttachmentsForSend\(attachmentOverride \?\? attachedFiles, quoteScopeAtSend, explicitComposerAction \|\| !!attachmentOverride\)/)
  assert.match(chat, /previous\.filter\(file => !currentAttachments\.includes\(file\)\)/)
  assert.match(chat, /quoteScopeAtSend !== quoteConversationRef\.current/)
  assert.match(chat, /setQuoteGeneration\(value => value \+ 1\)/)
})
