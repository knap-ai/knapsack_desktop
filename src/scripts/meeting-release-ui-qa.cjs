const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require(process.env.KNAPSACK_QA_PLAYWRIGHT_PATH || 'playwright')
const output = process.env.KNAPSACK_RELEASE_QA_OUTPUT || path.resolve(__dirname, '../../../review/evidence')
const url = process.env.KNAPSACK_RELEASE_QA_URL || 'http://127.0.0.1:1466/qa-fixtures/meeting-release.html'
;(async () => {
  fs.mkdirSync(output, { recursive: true })
  const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--no-first-run', '--disable-background-networking'] })
  try {
    const page = await browser.newPage({ viewport: { width: 1300, height: 900 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.route('**/*', route => new URL(route.request().url()).origin === new URL(url).origin ? route.continue() : route.abort())
    await page.goto(url)
    const input = page.getByTestId('qa-clawd-chat-input')
    await input.waitFor()
    const layout = async () => {
      const panel = await page.getByRole('region', { name: 'Meeting chat fixture' }).boundingBox()
      const controls = await page.locator('.ClawdChatInput').boundingBox()
      assert(controls.y >= panel.y && controls.y + controls.height <= panel.y + panel.height + 1, 'composer must remain inside panel with review and overflowing history')
      const field = await input.boundingBox(), voice = await page.locator('.ClawdVoiceToggle').boundingBox()
      assert(field.x + field.width <= voice.x + 1, 'voice control must not overlap textarea or scrollbar')
      assert(await page.locator('.ClawdChatInput').evaluate(el => el.scrollWidth <= el.clientWidth + 1), 'composer must fit narrow width')
    }
    await layout()
    await input.fill('Synthetic first message'); await page.getByRole('button', { name: 'Send', exact: true }).click()
    assert.deepEqual(await page.evaluate(() => window.releaseQA.chats), ['Synthetic first message'])
    await page.getByRole('button', { name: '560px', exact: true }).click()
    await input.fill(Array.from({ length: 8 }, (_, i) => `Synthetic line ${i + 1}`).join('\n'))
    await page.waitForTimeout(100); await layout()
    await page.screenshot({ path: path.join(output, 'meeting-composer-narrow.png') })
    await page.getByRole('button', { name: 'Toggle busy', exact: true }).click(); await layout()
    await page.getByRole('button', { name: '📋 Queue', exact: true }).click()
    assert.equal((await page.evaluate(() => window.releaseQA.chats)).length, 2)
    await page.getByRole('button', { name: 'Connections', exact: true }).click()
    assert.equal(await page.getByRole('heading', { name: 'work@example.test', exact: true }).count(), 1)
    assert.equal(await page.getByRole('heading', { name: 'Gmail', exact: true }).count(), 1)
    const first = page.locator('[data-grant-id="101"]')
    await first.getByRole('button', { name: 'Remove', exact: true }).click()
    await first.getByRole('button', { name: 'Cancel', exact: true }).click()
    assert.deepEqual(await page.evaluate(() => window.releaseQA.removals), [])
    await first.getByRole('button', { name: 'Remove', exact: true }).click()
    await first.getByRole('button', { name: 'Remove this connection', exact: true }).click()
    await first.waitFor({ state: 'detached' })
    assert.deepEqual(await page.evaluate(() => window.releaseQA.removals), [101])
    assert.equal(await page.locator('[data-grant-id="102"]').count(), 1)
    await page.screenshot({ path: path.join(output, 'meeting-connections-grouped.png') })
    await page.getByRole('button', { name: 'Email', exact: true }).click()
    const send = page.getByRole('button', { name: 'Send Email', exact: true })
    assert(await send.isDisabled())
    await page.getByRole('combobox', { name: 'Sender mailbox' }).selectOption('gmail|work|profile-a')
    await page.getByRole('textbox', { name: 'Email body' }).fill('Synthetic revised draft kept after rejection.')
    await page.evaluate(() => { window.releaseQA.failMail = true })
    await send.click()
    await page.getByRole('alert').filter({ hasText: 'Synthetic send rejection' }).waitFor()
    assert((await page.getByRole('textbox', { name: 'Email body' }).innerText()).includes('Synthetic revised draft'))
    assert.equal((await page.evaluate(() => window.releaseQA.sends)).length, 1)
    await page.screenshot({ path: path.join(output, 'meeting-email-retry.png') })
    await page.evaluate(() => { window.releaseQA.failMail = false })
    await send.click(); await page.getByText('✓ Email sent!', { exact: true }).waitFor()
    assert.equal((await page.evaluate(() => window.releaseQA.sends)).length, 2)
    assert.deepEqual(errors, [])
    console.log('PASS: bounded composer at760/560px, multiline/queue, grouped accounts, cancel/exact-grant removal, explicit sender and preserved-draft send retry; all sends/removals synthetic.')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
